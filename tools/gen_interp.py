#!/usr/bin/env python3
"""Generate src/m68k_interp.c: the 68000 fallback interpreter (one handler
per distinct opcode body, 65536-entry dispatch table)."""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from m68kgen import decode

out_path = sys.argv[1] if len(sys.argv) > 1 else 'src/m68k_interp.c'
bodies = {}
table = []
for op in range(65536):
    c = decode(op, 'interp')
    if c is None:
        table.append('h_illegal')
        continue
    body = list(c.out)
    if c.cycles:
        body.append('cpu.cyc += %d;' % c.cycles)
    key = '\n'.join(body)
    if key not in bodies:
        bodies[key] = ('h_%04X' % op, c.disasm())
    table.append(bodies[key][0])

with open(out_path, 'w') as f:
    f.write('/* GENERATED by tools/gen_interp.py - do not edit */\n#include "m68k.h"\n\n')
    f.write('static void h_illegal(void) {\n'
            '    if ((cpu.ir >> 12) == 0xA) m68k_exception(10, cpu.ppc);\n'
            '    else if ((cpu.ir >> 12) == 0xF) m68k_exception(11, cpu.ppc);\n'
            '    else m68k_exception(4, cpu.ppc);\n'
            '    cpu.cyc += 34;\n}\n\n')
    for key, (name, dis) in bodies.items():
        f.write('/* e.g. %s */\nstatic void %s(void) {\n' % (dis.replace('*/', ''), name))
        for line in key.split('\n'):
            if line:
                f.write('    %s\n' % line)
        f.write('}\n')
    f.write('\nvoid (*const m68k_optable[65536])(void) = {\n')
    for i in range(0, 65536, 8):
        f.write('    ' + ', '.join(table[i:i + 8]) + ',\n')
    f.write('};\n')
print('%d distinct handlers' % len(bodies), file=sys.stderr)
